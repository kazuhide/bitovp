/** Canonical names keep imported API wire values editable in the same selects. */
export function codecEnumSchema(name: CodecEnumName) {
	const values: Readonly<Record<string, string>> = CODEC_ENUM_VALUES[name];
	return z.string().transform((value, ctx) => {
		if (Object.hasOwn(values, value) && typeof values[value] === "string")
			return value;
		const alias = Object.entries(values).find(([, wire]) => wire === value);
		if (alias) return alias[0];
		ctx.addIssue({
			code: "custom",
			message: `Invalid ${name}: expected a supported enum name or wire value`,
		});
		return z.NEVER;
	});
}
