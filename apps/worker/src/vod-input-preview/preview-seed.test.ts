import { createHash } from "node:crypto";
import { Readable } from "node:stream";
import {
	GetObjectCommand,
	HeadObjectCommand,
	PutObjectCommand,
	type S3Client,
} from "@aws-sdk/client-s3";
import { describe, expect, it, vi } from "vitest";
import {
	ensurePreviewFixture,
	PreviewFixtureSeedError,
	previewSeedFailureReason,
	VOD_PREVIEW_FIXTURE_MAX_BYTES,
} from "./preview-seed";

const bytes = Buffer.from("immutable legacy fixture");
const sha256 = (body: Uint8Array) =>
	createHash("sha256").update(body).digest("hex");
const meta = () => ({
	ContentLength: bytes.length,
	ETag: '"pinned-v1"',
	Metadata: { sha256: sha256(bytes), "preview-fixture": "vod-timeline-v1" },
});
const input = (
	send: ReturnType<typeof vi.fn>,
	generate = vi.fn(async () => Buffer.from("different re-encode")),
) => ({
	client: { send } as unknown as Pick<S3Client, "send">,
	bucket: "isolated",
	key: "fixtures/vod-timeline/v1/a.mp4",
	contentType: "video/mp4",
	fixtureTag: "vod-timeline-v1",
	generate,
});

describe("immutable isolated preview fixture seeding", () => {
	it("preserves existing bytes despite a different possible re-encode and never calls the generator or PUT", async () => {
		const send = vi.fn(async (command: unknown) => {
			if (command instanceof HeadObjectCommand) return meta();
			if (command instanceof GetObjectCommand)
				return { ...meta(), Body: Readable.from([bytes]) };
			throw new Error("Existing object must not be written");
		});
		const request = input(send);
		expect(await ensurePreviewFixture(request)).toMatchObject({
			status: "PRESERVED",
			sha256: sha256(bytes),
		});
		expect(request.generate).not.toHaveBeenCalled();
		expect(send.mock.calls.map(([command]) => command)).not.toContainEqual(
			expect.any(PutObjectCommand),
		);
	});
	it("rejects a fixture marker mismatch even when the saved hash equals the generated bytes", async () => {
		const send = vi.fn(async () => ({
			...meta(),
			Metadata: { sha256: sha256(bytes), "preview-fixture": "another-fixture" },
		}));
		await expect(
			ensurePreviewFixture(
				input(
					send,
					vi.fn(async () => bytes),
				),
			),
		).rejects.toMatchObject({ code: "PREVIEW_FIXTURE_METADATA_INVALID" });
	});
	it("creates missing bytes conditionally and verifies the stored body", async () => {
		let exists = false;
		const send = vi.fn(async (command: unknown) => {
			if (command instanceof HeadObjectCommand) {
				if (!exists)
					throw Object.assign(new Error("missing"), { name: "NotFound" });
				return meta();
			}
			if (command instanceof PutObjectCommand) {
				expect(command.input.IfNoneMatch).toBe("*");
				exists = true;
				return {};
			}
			if (command instanceof GetObjectCommand)
				return { ...meta(), Body: Readable.from([bytes]) };
			throw new Error("Unexpected command");
		});
		const request = input(
			send,
			vi.fn(async () => bytes),
		);
		expect(await ensurePreviewFixture(request)).toMatchObject({
			status: "CREATED",
			sha256: sha256(bytes),
		});
		expect(await ensurePreviewFixture(request)).toMatchObject({
			status: "PRESERVED",
			sha256: sha256(bytes),
		});
		expect(request.generate).toHaveBeenCalledOnce();
		expect(
			send.mock.calls.filter(
				([command]) => command instanceof PutObjectCommand,
			),
		).toHaveLength(1);
		expect(send.mock.calls.map(([command]) => command)).toContainEqual(
			expect.any(GetObjectCommand),
		);
	});
	it("pins GET to the exact HEAD ETag and version and disposes its stream", async () => {
		const body = Readable.from([bytes.subarray(0, 3), bytes.subarray(3)]);
		const send = vi.fn(
			async (command: unknown, options: { abortSignal?: AbortSignal }) => {
				expect(options.abortSignal).toBeInstanceOf(AbortSignal);
				if (command instanceof HeadObjectCommand)
					return { ...meta(), VersionId: "version-1" };
				if (command instanceof GetObjectCommand) {
					expect(command.input).toMatchObject({
						IfMatch: '"pinned-v1"',
						VersionId: "version-1",
					});
					return { ...meta(), VersionId: "version-1", Body: body };
				}
				throw new Error("No writes");
			},
		);
		await ensurePreviewFixture(input(send));
		expect(body.destroyed).toBe(true);
	});
	it.each([
		["empty", { ContentLength: 0 }, "PREVIEW_FIXTURE_SIZE_INVALID"],
		[
			"oversized",
			{ ContentLength: VOD_PREVIEW_FIXTURE_MAX_BYTES + 1 },
			"PREVIEW_FIXTURE_SIZE_INVALID",
		],
		["noninteger", { ContentLength: 1.5 }, "PREVIEW_FIXTURE_SIZE_INVALID"],
		["no etag", { ETag: " " }, "PREVIEW_FIXTURE_METADATA_INVALID"],
		[
			"bad sha",
			{ Metadata: { sha256: "BAD", "preview-fixture": "vod-timeline-v1" } },
			"PREVIEW_FIXTURE_METADATA_INVALID",
		],
	] as const)("rejects %s HEAD before reading or generating", async (_name, patch, code) => {
		const send = vi.fn(async () => ({ ...meta(), ...patch }));
		const request = input(send);
		await expect(ensurePreviewFixture(request)).rejects.toMatchObject({ code });
		expect(send).toHaveBeenCalledOnce();
		expect(request.generate).not.toHaveBeenCalled();
	});
	it.each([
		["changed etag", { ETag: '"changed"' }, bytes, "PREVIEW_FIXTURE_CHANGED"],
		[
			"changed version",
			{ VersionId: "changed" },
			bytes,
			"PREVIEW_FIXTURE_CHANGED",
		],
		[
			"wrong length",
			{ ContentLength: 1 },
			bytes,
			"PREVIEW_FIXTURE_SIZE_INVALID",
		],
		["short body", {}, bytes.subarray(1), "PREVIEW_FIXTURE_SIZE_INVALID"],
		[
			"long body",
			{},
			Buffer.concat([bytes, Buffer.from("extra")]),
			"PREVIEW_FIXTURE_SIZE_INVALID",
		],
		[
			"corrupt body",
			{},
			Buffer.alloc(bytes.length, 0),
			"PREVIEW_FIXTURE_SHA_MISMATCH",
		],
	] as const)("refuses %s without overwriting and closes the GET body", async (_name, patch, content, code) => {
		const body = Readable.from([content]);
		const send = vi.fn(async (command: unknown) => {
			if (command instanceof HeadObjectCommand)
				return { ...meta(), VersionId: "version-1" };
			if (command instanceof GetObjectCommand)
				return { ...meta(), VersionId: "version-1", ...patch, Body: body };
			throw new Error("No writes");
		});
		const request = input(send);
		await expect(ensurePreviewFixture(request)).rejects.toMatchObject({ code });
		expect(request.generate).not.toHaveBeenCalled();
		expect(body.destroyed).toBe(true);
	});
	it.each([
		404, 412,
	])("does not adopt a changed object after a GET %s", async (httpStatusCode) => {
		const send = vi.fn(async (command: unknown) => {
			if (command instanceof HeadObjectCommand) return meta();
			throw { $metadata: { httpStatusCode } };
		});
		await expect(ensurePreviewFixture(input(send))).rejects.toMatchObject({
			code: "PREVIEW_FIXTURE_CHANGED",
		});
	});
	it("does not treat a forbidden HEAD as a missing object", async () => {
		const send = vi.fn(async () => {
			throw Object.assign(new Error("secret-in-sdk-message"), {
				name: "NoSuchKey",
				$metadata: { httpStatusCode: 403 },
			});
		});
		const request = input(send);
		await expect(ensurePreviewFixture(request)).rejects.toMatchObject({
			code: "PREVIEW_FIXTURE_READ_FAILED",
		});
		expect(request.generate).not.toHaveBeenCalled();
	});
	it("preserves a concurrent conditional create rather than overwriting it", async () => {
		let exists = false;
		const send = vi.fn(async (command: unknown) => {
			if (command instanceof HeadObjectCommand) {
				if (!exists) throw { $metadata: { httpStatusCode: 404 } };
				return meta();
			}
			if (command instanceof PutObjectCommand) {
				expect(command.input.IfNoneMatch).toBe("*");
				exists = true;
				throw { $metadata: { httpStatusCode: 412 } };
			}
			if (command instanceof GetObjectCommand)
				return { ...meta(), Body: Readable.from([bytes]) };
			throw new Error("Unexpected command");
		});
		expect(await ensurePreviewFixture(input(send))).toMatchObject({
			status: "PRESERVED",
			sha256: sha256(bytes),
		});
		expect(
			send.mock.calls.filter(
				([command]) => command instanceof PutObjectCommand,
			),
		).toHaveLength(1);
	});
	it.each([
		"timeout",
		"cancel",
	] as const)("bounds a stalled body on %s and removes sensitive abort reasons", async (mode) => {
		const controller = new AbortController();
		const body = new Readable({ read() {} });
		const send = vi.fn(async (command: unknown) =>
			command instanceof HeadObjectCommand ? meta() : { ...meta(), Body: body },
		);
		const request = input(send);
		const timer =
			mode === "cancel"
				? setTimeout(
						() => controller.abort(new Error("secret abort reason")),
						10,
					)
				: undefined;
		try {
			await expect(
				ensurePreviewFixture({
					...request,
					timeoutMs: 30,
					signal: controller.signal,
				}),
			).rejects.toMatchObject({
				code:
					mode === "cancel"
						? "PREVIEW_FIXTURE_CANCELED"
						: "PREVIEW_FIXTURE_TIMED_OUT",
			});
			expect(body.destroyed).toBe(true);
			expect(request.generate).not.toHaveBeenCalled();
		} finally {
			clearTimeout(timer);
			body.destroy();
		}
	});
	it("disposes a late GET response after its request deadline", async () => {
		const body = new Readable({ read() {} });
		let complete: ((value: unknown) => void) | undefined;
		const send = vi.fn(async (command: unknown) =>
			command instanceof HeadObjectCommand
				? meta()
				: await new Promise((resolve) => {
						complete = resolve;
					}),
		);
		await expect(
			ensurePreviewFixture({ ...input(send), timeoutMs: 10 }),
		).rejects.toMatchObject({ code: "PREVIEW_FIXTURE_TIMED_OUT" });
		complete?.({ ...meta(), Body: body });
		await new Promise((resolve) => setImmediate(resolve));
		expect(body.destroyed).toBe(true);
	});
	it("exposes only fixed reason codes for errors with arbitrary sensitive data", () => {
		for (const error of [
			new Error("s3://secret:password@example"),
			{ code: "secret-api-key", message: "secret" },
			null,
		]) {
			expect(previewSeedFailureReason(error)).toBe(
				"PREVIEW_SEED_UNEXPECTED_ERROR",
			);
		}
		expect(
			previewSeedFailureReason(
				new PreviewFixtureSeedError("PREVIEW_FIXTURE_SHA_MISMATCH"),
			),
		).toBe("PREVIEW_FIXTURE_SHA_MISMATCH");
		expect(
			previewSeedFailureReason(new Error("PREVIEW_ENVIRONMENT_REQUIRED")),
		).toBe("PREVIEW_ENVIRONMENT_REQUIRED");
	});
});
