import { describe, expect, it } from "vitest";
import {
	aisaChannelViewerProjection,
	aisaPublisherConnectionAllowed,
	isAisaLiveChannelView,
} from "./live-channel-aisa-view";

const analysisId = "bbbbbbbb-bbbb-4bbb-bbbb-bbbbbbbbbbbb";
const encodingId = "cccccccc-cccc-4ccc-8ccc-cccccccccccc";
const snapshot = {
	analysisId,
	encodingId,
	sequence: 1,
	producedAt: "2026-11-07T00:00:00.000Z",
	mediaTimeOriginUnixMs: 1790000000000,
	isFinal: true,
	analyzedStartTimeSeconds: 0,
	analyzedEndTimeSeconds: 5,
	metadata: { version: "test", disclaimer: "Generated by Bitmovin AI" },
	observations: [],
	keyMoments: [],
	sourceGaps: [],
};

describe("AISA viewer projection boundary", () => {
	it("preserves current-run monitoring through an allowlist while removing connection aliases", () => {
		const at = "2026-11-07T00:00:05.000Z";
		const raw = {
			timestamp: at,
			ingest: {
				status: "CONNECTED",
				healthy: true,
				droppedPacketsVideo: 4,
				streams: [
					{
						mediaType: "VIDEO",
						rate: 30,
						incomingBitrate: 900,
						url: "private",
					},
				],
				streamKey: "private",
			},
			output: {
				manifests: {
					hls: [
						{
							url: "private",
							manifestUpdates: [{ manifestUpdateWallClockTime: at }],
						},
					],
				},
			},
			message: "private",
		};
		const poll = {
			at,
			raw,
			deltas: { droppedPacketsVideo: 1, secret: "private" },
		};
		const run = {
			id: "run",
			bitmovinEncodingId: encodingId,
			createdAt: new Date("2026-11-07T00:00:00Z"),
			lastHeartbeat: poll,
		};
		const body = aisaChannelViewerProjection(
			{
				id: "channel",
				lastHeartbeat: { at, raw: { ingest: { status: "DISCONNECTED" } } },
			},
			run,
			{
				observedNow: new Date("2026-11-07T00:00:10Z"),
				heartbeatReception: {
					state: "available",
					runId: "run",
					configuredIntervalS: 2,
					latest: { receivedAt: at, sampledAt: at, raw },
					previousReceivedAt: null,
				},
			},
		);
		expect(body.lastHeartbeat).toEqual(body.currentRun?.lastHeartbeat);
		expect(body.lastHeartbeat).toMatchObject({
			at,
			raw: {
				ingest: { status: "CONNECTED", healthy: true, streams: [{ rate: 30 }] },
			},
			deltas: { droppedPacketsVideo: 1 },
		});
		expect(body.heartbeatReception).toMatchObject({
			state: "available",
			runId: "run",
			latest: { sampledAt: at, raw: { ingest: { status: "CONNECTED" } } },
		});
		expect(body.serverNow).toBe("2026-11-07T00:00:10.000Z");
		expect(body.monitoringSafeForViewer).toBe(true);
		expect(JSON.stringify(body)).not.toContain("private");
		expect(raw.ingest.streamKey).toBe("private");
	});

	it.each([
		"encoding",
		"birth",
	])("withholds monitoring when the persisted run %s binding is absent", (missing) => {
		const at = "2026-11-07T00:00:05.000Z";
		const raw = { timestamp: at, ingest: { status: "CONNECTED" } };
		const body = aisaChannelViewerProjection(
			{},
			{
				id: "run",
				bitmovinEncodingId: missing === "encoding" ? null : encodingId,
				createdAt:
					missing === "birth" ? undefined : new Date("2026-11-07T00:00:00Z"),
				lastHeartbeat: { at, raw },
			},
			{
				heartbeatReception: {
					state: "available",
					runId: "run",
					latest: { sampledAt: at, receivedAt: at, raw },
				},
			},
		);
		expect(body.currentRun?.lastHeartbeat).toBeNull();
		expect(body.heartbeatReception).toEqual({
			state: "unavailable",
			runId: "run",
		});
	});

	it("does not fall back to a previous airing's channel mirror or a foreign Push run", () => {
		const body = aisaChannelViewerProjection(
			{
				lastHeartbeat: {
					at: "2026-11-07T00:00:05Z",
					raw: { ingest: { status: "CONNECTED" } },
				},
			},
			{
				id: "current",
				createdAt: new Date("2026-11-07T00:00:00Z"),
				lastHeartbeat: { at: "bad", raw: { ingest: { healthy: "bad" } } },
			},
			{
				heartbeatReception: {
					state: "available",
					runId: "previous",
					latest: { raw: { ingest: { healthy: true } } },
				},
			},
		);
		expect(body.lastHeartbeat).toBeNull();
		expect(body.currentRun?.lastHeartbeat).toBeNull();
		expect(body.heartbeatReception).toEqual({
			state: "unavailable",
			runId: "current",
		});
	});

	it("keeps imported and run-bound channels protected without requiring a parseable managed plan", () => {
		expect(
			isAisaLiveChannelView({ origin: "AISA_IMPORTED", plan: null }, null),
		).toBe(true);
		expect(
			isAisaLiveChannelView({ plan: null }, { aisaAnalysisId: analysisId }),
		).toBe(true);
		expect(
			isAisaLiveChannelView(
				{ plan: { start: { aiSceneAnalysisLive: null } } },
				null,
			),
		).toBe(true);
		expect(
			isAisaLiveChannelView(
				{ plan: { start: { streamKey: "ordinary" } } },
				null,
			),
		).toBe(false);
	});

	it("protects partial AISA metadata when an Analysis id was not retained", () => {
		expect(
			isAisaLiveChannelView({ plan: null }, { aisaStatus: "RUNNING" }),
		).toBe(true);
		expect(
			isAisaLiveChannelView({ plan: null }, { aisaSnapshot: snapshot }),
		).toBe(true);
		expect(
			isAisaLiveChannelView(
				{ plan: null },
				{ aisaAnalysisId: null, aisaStatus: null, aisaSnapshot: null },
			),
		).toBe(false);
	});

	it("does not infer publisher permission from an incomplete or unknown authentication context", () => {
		expect(
			aisaPublisherConnectionAllowed({ actor: "user:admin", role: "ADMIN" }),
		).toBe(false);
		expect(
			aisaPublisherConnectionAllowed({
				actor: "token:admin",
				role: "ADMIN",
				isImpersonating: false,
			}),
		).toBe(false);
		expect(
			aisaPublisherConnectionAllowed({
				actor: "unexpected",
				role: "ADMIN",
				isImpersonating: false,
			}),
		).toBe(false);
	});

	it.each([
		{ ...snapshot, analysisId: "aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa" },
		{ ...snapshot, encodingId: "aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa" },
		{ ...snapshot, sequence: -1 },
	])("retains ordinary run identity while withholding Analysis metadata %#", (aisaSnapshot) => {
		const body = aisaChannelViewerProjection(
			{ id: "channel" },
			{
				id: "run",
				aisaAnalysisId: analysisId,
				bitmovinEncodingId: encodingId,
				aisaSnapshot,
			},
		);
		expect(body.currentRun).toMatchObject({
			id: "run",
			aisaAnalysisId: null,
			bitmovinEncodingId: encodingId,
			aisaSnapshot: null,
		});
	});

	it("does not mutate persisted records and withholds the entire private snapshot", () => {
		const run = {
			id: "run",
			aisaAnalysisId: analysisId,
			bitmovinEncodingId: encodingId,
			aisaSnapshot: {
				...snapshot,
				ingest: { streamKey: "private" },
				metadata: { ...snapshot.metadata, encoderIp: "private" },
			},
			stepLog: [{ request: "private" }],
		};
		const channel = {
			id: "channel",
			futurePublisherAlias: "private",
			plan: { start: { streamKey: "private" } },
		};
		const before = JSON.stringify({ channel, run });
		const body = aisaChannelViewerProjection(channel, run);
		expect(body.currentRun?.aisaSnapshot).toBeNull();
		expect(body.currentRun?.aisaAnalysisId).toBeNull();
		expect(JSON.stringify(body)).not.toContain("private");
		expect(JSON.stringify({ channel, run })).toBe(before);
	});

	it("protects a never-provisioned managed channel without inventing a current run", () => {
		const body = aisaChannelViewerProjection(
			{ id: "channel", streamKey: "private" },
			null,
		);
		expect(body.currentRun).toBeNull();
		expect(body.heartbeatReception).toEqual({
			state: "unavailable",
			runId: null,
		});
		expect(body.streamKey).toBeNull();
	});
});
