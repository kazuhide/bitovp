import { beforeEach, describe, expect, it, vi } from "vitest";

type Principal = {
	actor: string;
	role: string;
	isImpersonating: boolean;
	tokenRoleKnown?: boolean;
};
const mocks = vi.hoisted(() => ({
	findUnique: vi.fn(),
	credentialFindMany: vi.fn(),
	heartbeatEvents: vi.fn(),
	tenant: undefined as Principal | undefined,
}));
vi.mock("@/lib/server/context", () => ({
	getServerContext: () => ({
		tenant: mocks.tenant,
		prisma: {
			liveChannel: { findUnique: mocks.findUnique },
			credential: { findMany: mocks.credentialFindMany },
			webhookRegistration: { findFirst: vi.fn().mockResolvedValue(null) },
			webhookEvent: { findMany: mocks.heartbeatEvents },
			appSetting: { findUnique: vi.fn().mockResolvedValue(null) },
		},
	}),
}));

import { GET } from "./route";

const channelId = "00000000-0000-4000-8000-0000000000c0";
const accountId = "aaaaaaaa-aaaa-4aaa-aaaa-aaaaaaaaaaaa";
const analysisId = "bbbbbbbb-bbbb-4bbb-bbbb-bbbbbbbbbbbb";
const encodingId = "cccccccc-cccc-4ccc-8ccc-cccccccccccc";
const secret = "publisher-private-connection";
const snapshot = {
	analysisId,
	encodingId,
	sequence: 1,
	producedAt: "2026-11-07T00:00:00.000Z",
	mediaTimeOriginUnixMs: 1790000000000,
	isFinal: false,
	analyzedStartTimeSeconds: 0,
	analyzedEndTimeSeconds: 5,
	metadata: { version: "test", disclaimer: "Generated by Bitmovin AI" },
	observations: [
		{
			id: "observation",
			text: "A goal",
			startTimeSeconds: 1,
			endTimeSeconds: 3,
		},
	],
	keyMoments: [],
	sourceGaps: [],
};

function managedRow() {
	return {
		id: channelId,
		name: "AISA channel",
		origin: "MANAGED",
		status: "RUNNING",
		bitmovinAccountId: accountId,
		bitmovinEncodingId: encodingId,
		plan: {
			start: {
				aiSceneAnalysisLive: { preset: "AISA_PREVIEW_MANAGED" } as
					| { preset: string }
					| null
					| undefined,
				streamKey: secret,
			},
			liveInput: { url: `rtmp://encoder.invalid/live/${secret}` },
		},
		stepLog: [
			{
				payload: { request: { input: { streamKey: secret } } },
				message: secret,
			},
		],
		streamKey: secret,
		encoderIp: secret,
		lastHeartbeat: { raw: { unexpectedConnection: secret } },
		liveToVod: { unknownPublisherInfo: secret },
		error: secret,
		futurePublisherResponse: { url: secret },
		createdAt: new Date("2026-11-07T00:00:00Z"),
		runs: [
			{
				id: "run-1",
				seq: 1,
				status: "RUNNING",
				cancelRequested: false,
				bitmovinEncodingId: encodingId,
				aisaAnalysisId: analysisId as string | null,
				aisaStatus: "RUNNING" as string | null,
				aisaObservedAt: new Date("2026-11-07T00:00:05Z"),
				aisaSnapshot: {
					...snapshot,
					rtmpIngest: { streamKey: secret },
				} as unknown,
				streamKey: secret,
				encoderIp: secret,
				stepLog: [{ payload: { compiledStartRequest: secret } }],
				lastHeartbeat: { raw: { unexpectedConnection: secret } },
				liveToVod: { unknownPublisherInfo: secret },
				originObservation: { url: secret },
				error: secret,
				createdAt: new Date("2026-11-07T00:00:00Z"),
			},
		] satisfies [Record<string, unknown>],
	};
}
function request() {
	return new Request(`http://test/api/live-channels/${channelId}`, {
		// Only fresh server context has authority; these are deliberately stronger.
		headers: { "x-bitovp-actor": "user:forged", "x-bitovp-role": "ADMIN" },
	});
}
const params = () => ({ params: Promise.resolve({ id: channelId }) });

beforeEach(() => {
	vi.clearAllMocks();
	mocks.tenant = {
		actor: "user:viewer",
		role: "VIEWER",
		isImpersonating: false,
	};
	mocks.findUnique.mockResolvedValue(managedRow());
	mocks.credentialFindMany.mockResolvedValue([]);
	mocks.heartbeatEvents.mockResolvedValue([]);
});

describe("AISA publisher connection projection", () => {
	it("strips every publisher connection container while preserving viewer Analysis reads", async () => {
		const response = await GET(request(), params());
		expect(response.status).toBe(200);
		const body = await response.json();
		expect(JSON.stringify(body)).not.toContain(secret);
		expect(body.plan.start.aiSceneAnalysisLive).toEqual({
			preset: "AISA_PREVIEW_MANAGED",
		});
		expect(body.plan.start.streamKey).toBeUndefined();
		expect(body.streamKey).toBeNull();
		expect(body.encoderIp).toBeNull();
		expect(body.stepLog).toEqual([]);
		expect(body.lastHeartbeat).toBeNull();
		expect(body.currentRun.aisaSnapshot).toEqual(snapshot);
		expect(body.currentRun).toMatchObject({
			id: "run-1",
			seq: 1,
			aisaAnalysisId: analysisId,
			bitmovinEncodingId: encodingId,
			aisaStatus: "RUNNING",
			streamKey: null,
			encoderIp: null,
			stepLog: [],
			lastHeartbeat: null,
		});
		expect(body.bitmovinAccountId).toBe(accountId);
		expect(body.technicalDetailsAllowed).toBe(false);
		expect(body.heartbeatReception).toEqual({
			state: "unavailable",
			runId: "run-1",
		});
		expect(response.headers.get("Cache-Control")).toContain("no-store");
		expect(mocks.heartbeatEvents).not.toHaveBeenCalled();
		expect(mocks.credentialFindMany).not.toHaveBeenCalled();
	});

	it.each([
		undefined,
		{ actor: "user:missing-role", role: "UNKNOWN", isImpersonating: false },
		{ actor: "anonymous", role: "ADMIN", isImpersonating: false },
		{ actor: "token:unresolved", role: "ADMIN", isImpersonating: false },
		{
			actor: "token:legacy",
			role: "ADMIN",
			isImpersonating: false,
			tokenRoleKnown: false,
		},
		{
			actor: "token:viewer",
			role: "VIEWER",
			isImpersonating: false,
			tokenRoleKnown: true,
		},
		{ actor: "user:owner", role: "ADMIN", isImpersonating: true },
	])("fails closed for an unresolved or restricted principal %#", async (principal) => {
		mocks.tenant = principal;
		const body = await (await GET(request(), params())).json();
		expect(JSON.stringify(body)).not.toContain(secret);
		expect(body.currentRun.aisaAnalysisId).toBe(analysisId);
	});

	it.each([
		{ actor: "user:operator", role: "OPERATOR", isImpersonating: false },
		{ actor: "user:admin", role: "ADMIN", isImpersonating: false },
		{
			actor: "token:operator",
			role: "OPERATOR",
			isImpersonating: false,
			tokenRoleKnown: true,
		},
		{ actor: "session", role: "ADMIN", isImpersonating: false },
		{ actor: "none", role: "ADMIN", isImpersonating: false },
	])("preserves the existing trusted publisher response %#", async (principal) => {
		mocks.tenant = principal;
		const response = await GET(request(), params());
		const body = await response.json();
		expect(body.plan.start.streamKey).toBe(secret);
		expect(body.streamKey).toBe(secret);
		expect(body.currentRun.encoderIp).toBe(secret);
		expect(body.currentRun.stepLog).toEqual(managedRow().runs[0].stepLog);
		expect(response.headers.get("Cache-Control")).toContain("no-store");
	});

	it.each([
		"AISA_IMPORTED",
		"run-binding",
		"malformed-setting",
	])("projects AISA identity even when the normal plan marker is absent: %s", async (kind) => {
		const row = managedRow();
		if (kind === "AISA_IMPORTED") row.origin = "AISA_IMPORTED";
		if (kind === "run-binding") row.plan.start.aiSceneAnalysisLive = undefined;
		if (kind === "malformed-setting") row.plan.start.aiSceneAnalysisLive = null;
		mocks.findUnique.mockResolvedValue(row);
		const body = await (await GET(request(), params())).json();
		expect(JSON.stringify(body)).not.toContain(secret);
		expect(body.currentRun.aisaAnalysisId).toBe(analysisId);
	});

	it("leaves ordinary live channel response behavior unchanged for VIEWER", async () => {
		const row = managedRow();
		row.plan.start.aiSceneAnalysisLive = undefined;
		row.runs[0].aisaAnalysisId = null;
		row.runs[0].aisaStatus = null;
		row.runs[0].aisaSnapshot = null;
		mocks.findUnique.mockResolvedValue(row);
		const body = await (await GET(request(), params())).json();
		expect(body.plan.start.streamKey).toBe(secret);
		expect(body.streamKey).toBe(secret);
		expect(body.currentRun.encoderIp).toBe(secret);
	});
});
